"""End-to-end LLM numbers: tokens/s and perplexity with each linear-layer backend.

Speed (batch 1, greedy): prefill of a 64-token prompt, 128 decode steps after
it, and a separate 512-token prefill (``pp512``, llama-bench's default), for
every backend and thread count. Each configuration is run ``reps`` times after
a warm-up; like ``lowbit.bench`` we wait for an idle machine first and re-run a
rep when other processes used more than ``max_other`` cores during it. The
wall time of every forward pass is split into linear layers, LM head,
attention (RoPE, KV-cache write, QK^T, softmax, PV) and "other" (embedding,
RMSNorm, SiLU, residual adds, python) by ``Model.prof``.

Quality: perplexity on the first ``n_tokens`` tokens of a fixed text sample
(the head of the WikiText-2 raw test split, committed in ``lowbit/data``), in
non-overlapping windows of ``ctx`` tokens, each scored from its second token
(so every scored token sees 1..ctx-1 tokens of context). Top-1 agreement is the
fraction of scored positions where a backend's argmax equals fp32's.
"""
